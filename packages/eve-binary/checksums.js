/**
 * Deterministic checksum primitives shared by the ROM builder, the Studio
 * exporter, the simulator backend and tests.
 *
 * CRC32 uses the reflected IEEE polynomial 0xEDB88320 with init 0xFFFFFFFF and
 * final XOR 0xFFFFFFFF (the value reported by `cksum -a crc32` variants and by
 * the ROM header).
 *
 * SHA-256 is a dependency-free implementation so the same code runs in the
 * browser (WebCrypto is async) and in Node without conditional imports.
 */

const CRC32_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let index = 0; index < 256; index += 1) {
    let value = index;
    for (let bit = 0; bit < 8; bit += 1) {
      value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
    }
    table[index] = value >>> 0;
  }
  return table;
})();

export function crc32(bytes, start = 0, end = bytes.length) {
  let crc = 0xffffffff;
  for (let index = start; index < end; index += 1) {
    crc = CRC32_TABLE[(crc ^ bytes[index]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

export function fnv1a32(input) {
  const bytes = typeof input === 'string' ? new TextEncoder().encode(input) : input;
  let hash = 0x811c9dc5;
  for (let index = 0; index < bytes.length; index += 1) {
    hash ^= bytes[index];
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

export function toHex32(value) {
  return (value >>> 0).toString(16).padStart(8, '0').toUpperCase();
}

export function toHex(bytes) {
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
}

export function bytesEqual(a, b) {
  if (a.length !== b.length) return false;
  for (let index = 0; index < a.length; index += 1) {
    if (a[index] !== b[index]) return false;
  }
  return true;
}

